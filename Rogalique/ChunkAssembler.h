// Собирает уровень не из одного .tmj, а из нескольких: неизменный "хаб" (Resources/Level/rogalique.tmj —
// PlayerSpawn/Door там, как и сейчас) плюс случайно выбранные "чанки" из пула (см. poolDir — все .tmj в этой
// папке, сканируется на диске, новый файл подхватывается без правки кода), расставленные цепочками по 4 сторонам
// света (север/юг/восток/запад) от хаба.
//
// Конвенция для чанков пула: одинаковый размер (ширина==высота==poolChunkSizeTiles,
// чанк другого размера пропускается с LOG_WARN — не участвует в сборке этого запуска) и проход на ВСЕХ четырёх
// сторонах шириной ровно corridorWidth тайлов, centered (посередине каждой стороны) — тогда чанк одинаково хорошо
// встаёт и в середину цепочки (проход используется), и на самый край (сборщик сам заделывает стеной те выходы,
// что никуда не ведут — не нужно готовить отдельные "тупиковые" версии чанков).
struct ChunkAssemblerConfig {
    std::string hubPath = "Resources/Level/rogalique.tmj";
    std::string poolDir = "Resources/Level/Chunks";
    int poolChunkSizeTiles = 15; // Ожидаемый widthTiles==heightTiles каждого чанка пула.
    int chainLength = 2;         // Сколько чанков подряд в каждую из 4 сторон от хаба.
    int corridorWidth = 3;       // В тайлах — ширина прохода/коридора, тот же принцип, что в старой планировке.
    int corridorLength = 4;      // Зазор между соседними чанками (хаб<->чанк, чанк<->чанк) — сюда встаёт коридор.

    // Порядок — Север/Юг/Восток/Запад (тот же, что у Direction/ALL_DIRECTIONS в .cpp). Непустой путь — этот файл
    // ВСЕГДА встаёт ПОСЛЕДНИМ звеном цепочки в данную сторону (индекс chainLength-1), а не выбирается случайно из
    // poolDir, как остальные звенья — нужно, чтобы то, что там лежит (например, ключ от главной двери, см.
    // SceneFacade::run()), гарантированно попадало на карту КАЖДЫЙ забег, а не иногда пропадало из-за случайного
    // выбора (при выборе с повторением из пула ничего не гарантирует, что конкретный файл вообще будет вытянут).
    // Тот же размер/конвенция проёмов, что и у обычных чанков пула (poolChunkSizeTiles/corridorWidth) — отдельная
    // папка не нужна, можно (но не обязательно) держать эти файлы прямо в poolDir, сборщик просто не выберет их
    // случайно на не-последние звенья (см. .cpp — они не участвуют в общем рандомном пуле вовсе).
    std::array<std::string, 4> keyRoomPaths;
};

// false + LOG_ERROR, если хаб не загрузился или в пуле нет ни одного чанка подходящего размера — то же соглашение,
// что у loadTiledLevel(). seed — та же роль, что у остального контента уровня: одно и то же значение всегда даёт
// одну и ту же сборку (нужно для "Продолжить"/"Загрузить сохранение", как и раньше с рассадкой ботов/предметов).
bool assembleChunkedLevel(const ChunkAssemblerConfig& config, unsigned seed, TiledLevel& out);
