#pragma once
#include "IComponent.h"
#include <SFML/System/Time.hpp>

// Секундомер текущего забега — считает время, пока идёт активный геймплей (не на паузе, не после смерти/победы,
// см. update() в .cpp), останавливается ровно в момент победы (см. GameWorld::isVictory) и дальше не идёт, пока
// висит экран победы. reset() обнуляет — общий хвост тех же обработчиков меню, что сбрасывают весь остальной
// ростер ("Начать"/"Играть заново"/"В главное меню" и т.п., см. SceneFacade.cpp); "Продолжить"/"Загрузить
// сохранение" вместо reset() зовут setElapsed() с сохранённым значением (см. GameMemento::hasElapsedTimeData) —
// иначе таймер легко было бы обнулить пересохранением прямо перед финишем, занижая честное время в таблице лидеров.
// Живёт в UI-дереве (как и остальной HUD, см. HudTextComponent), поэтому тикает, даже когда мировое дерево
// (m_root) на паузе — иначе на экране паузы таймер сам не остановился бы вовремя (m_root просто не обновлялся бы,
// но объект в uiRoot — да).
class GameTimerComponent : public IComponent {
public:
    void update(sf::Time dt) override;
    void reset() override;

    sf::Time getElapsed() const
    {
        return m_elapsed;
    }

    // Восстанавливает секундомер на конкретное значение (см. SceneFacade.cpp — "Продолжить"/"Загрузить сохранение"
    // теперь продолжают отсчёт с момента сохранения, а не сбрасывают на ноль, иначе реальное время пробежки можно
    // было бы занизить пересохранением прямо перед финишем). m_stopped сбрасывается — победа ещё не наступила.
    void setElapsed(sf::Time elapsed)
    {
        m_elapsed = elapsed;
        m_stopped = false;
    }

private:
    sf::Time m_elapsed;
    bool m_stopped = false;
};
